/** أيقونة SVG (flip: عكسها لاتجاه اليمين لليسار) */
export function icon(name, { flip = false, size } = {}) {
  const ns = 'http://www.w3.org/2000/svg';
  const svg = document.createElementNS(ns, 'svg');
  svg.setAttribute('viewBox', '0 0 24 24');
  svg.setAttribute('class', 'icon');
  svg.setAttribute('aria-hidden', 'true');
  if (flip) svg.style.transform = 'scaleX(-1)';
  if (size) { svg.style.width = svg.style.height = `${size}px`; }
  const p = document.createElementNS(ns, 'path');
  p.setAttribute('d', PATHS[name] || '');
  svg.append(p);
  return svg;
}

let toastTimer = null;
export function toast(text, ms = 3500) {
  document.querySelector('.toast')?.remove();
  const t = h('div', { class: 'toast', role: 'status' }, text);
  document.body.append(t);
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => t.remove(), ms);
}

/** نافذة منبثقة؛ تعيد دالة لإغلاقها */
export function modal(build, { onClose } = {}) {
  const box = h('div', { class: 'dialog', role: 'dialog' });
  const ov = h('div', { class: 'overlay', onclick: (e) => { if (e.target === ov) close(); } }, box);
  const close = () => { ov.remove(); onClose?.(); };
  build(box, close);
  document.body.append(ov);
  return close;
}
